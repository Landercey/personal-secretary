"""界面层。

=====================================================================
为什么是网页界面，不是 tkinter
=====================================================================
旧项目用 tkinter（Python 自带，常驻 30 MB），但用户的原话是"界面太简陋"。
这不是没调好，是 tkinter 的能力上限：没有圆角、没有阴影、没有平滑滚动，
字体渲染也糙。

实测过另一个方案的代价（2026-10-09）：

    tkinter              约 30 MB    ← 做不到"高级"
    pywebview + WebView2  约 +436 MB  ← 要多少高级有多少

**关键是那 436 MB 只在窗口开着的时候占**，关掉立刻还回去
（实测 msedgewebview2 554 MB → 918 MB → 关掉回 554 MB）。
常驻的后台（收消息 + 定时推送）不需要界面，只有 40 MB。
所以"好看"和"省内存"不是二选一 —— 你一天看几分钟待办，那几分钟多花 436 MB。

而且 WebView2 是 Windows 10/11 **自带**的（实测这台是 154 版），
用户不用额外下载任何东西；pywebview 本体加绑定一共约 900 KB。

=====================================================================
结构
=====================================================================
    bridge.py   Python 和网页之间的桥：网页调它取数据
    index.html  界面本体（HTML + CSS + JS 全在这一个文件里）

界面**不直接连数据库** —— 数据一律经过 bridge，规则留在上层。
"""

